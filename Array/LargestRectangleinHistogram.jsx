const CHART_TARGET_W = 480;
const CHART_TARGET_H = 160;

function chartGeometry(H) {
  const slots = H.length + 1;                       // + the sentinel slot at i = n
  const maxH = H.length ? Math.max(...H, 1) : 1;
  const GAP = slots > 20 ? 3 : 6;
  const COL_W = Math.max(14, Math.min(40, Math.floor((CHART_TARGET_W + GAP) / slots) - GAP));
  const LEVELS = maxH + 1;
  const UNIT = Math.max(7, Math.min(26, Math.floor(CHART_TARGET_H / LEVELS)));
  const showNums = UNIT >= 14 && COL_W >= 20;
  return { slots, GAP, COL_W, UNIT, LEVELS, CHART_H: LEVELS * UNIT, showNums, xOf: (k) => k * (COL_W + GAP) };
}

function HistogramChart({ H, s }) {
  const n = H.length;
  const { slots, GAP, COL_W, UNIT, LEVELS, CHART_H, showNums, xOf } = chartGeometry(H);
  const inStack = new Set(s.stack);
  const isDone = new Set(s.done);
  const totalW = slots * COL_W + (slots - 1) * GAP;
  const spanW = (L, R) => xOf(R) + COL_W - xOf(L);

  return (
    <div style={{ overflowX: 'auto', padding: '26px 16px 8px' }}>
      <div style={{ width: totalW, margin: '0 auto' }}>
        <div style={{ position: 'relative', height: CHART_H, borderBottom: `1px solid ${C.border}` }}>
          {Array.from({ length: LEVELS }, (_, k) => (
            <div key={k} style={{
              position: 'absolute', left: 0, right: 0, bottom: k * UNIT,
              borderTop: `1px dashed ${C.border}55`,
            }} />
          ))}

          {/* bars */}
          {H.map((h, k) => {
            const popping = k === s.popped;
            const cur = k === s.i && !s.finished;
            const stacked = inStack.has(k);
            const resolved = isDone.has(k) && !popping;
            const unseen = k > s.i && !s.finished;

            let bd, bg, fg;
            if (popping)       { bd = C.orange; bg = C.orangeGlow; fg = C.orange; }
            else if (cur)      { bd = C.purple; bg = C.purpleGlow; fg = C.purple; }
            else if (stacked)  { bd = C.accent; bg = C.accentGlow; fg = C.accent; }
            else if (resolved || s.finished) { bd = C.dim; bg = C.surface2; fg = C.dim; }
            else if (unseen)   { bd = C.border + '70'; bg = 'transparent'; fg = C.dim + '80'; }
            else               { bd = C.dim; bg = C.surface2; fg = C.text; }

            return (
              <div key={k} style={{ position: 'absolute', left: xOf(k), bottom: 0, width: COL_W }}>
                {h > 0 && (
                  <div style={{
                    position: 'absolute', bottom: 0, left: 0, width: COL_W, height: h * UNIT,
                    background: bg,
                    borderTop: `2px solid ${bd}`, borderLeft: `2px solid ${bd}`, borderRight: `2px solid ${bd}`,
                    borderRadius: '5px 5px 0 0',
                    display: 'flex', alignItems: 'flex-start', justifyContent: 'center', paddingTop: 3,
                    fontFamily: mono, fontSize: 11, fontWeight: 700, color: fg, overflow: 'hidden',
                    filter: popping || cur ? `drop-shadow(0 0 10px ${popping ? C.orangeGlow : C.purpleGlow})` : 'none',
                    transition: 'all 0.4s cubic-bezier(0.4,0,0.2,1)',
                  }}>{showNums ? h : ''}</div>
                )}
                {h === 0 && (
                  <div style={{ position: 'absolute', bottom: 0, left: 0, width: COL_W, height: 3, borderRadius: 2, background: cur ? C.purple : C.border }} />
                )}
              </div>
            );
          })}

          {/* sentinel slot at i = n */}
          <div style={{
            position: 'absolute', left: xOf(n), bottom: 0, width: COL_W, height: 3, borderRadius: 2,
            background: s.i === n && !s.finished ? C.purple : C.border + '80',
            transition: 'all 0.4s',
          }} />

          {/* best rectangle so far */}
          {s.best && (
            <div style={{
              position: 'absolute', left: xOf(s.best.L) - 2, width: spanW(s.best.L, s.best.R) + 4,
              bottom: 0, height: s.best.h * UNIT + 2,
              borderTop: `2px solid ${C.green}`, borderLeft: `2px solid ${C.green}`, borderRight: `2px solid ${C.green}`,
              borderRadius: '4px 4px 0 0',
              background: s.finished ? C.greenGlow : 'transparent',
              pointerEvents: 'none', zIndex: 3,
              transition: 'all 0.4s cubic-bezier(0.4,0,0.2,1)',
            }}>
              <span style={{ position: 'absolute', right: 2, top: -16, fontFamily: mono, fontSize: 9, fontWeight: 700, color: C.green, whiteSpace: 'nowrap' }}>
                best={s.best.area}
              </span>
            </div>
          )}

          {/* rectangle being measured */}
          {s.rect && (
            <div style={{
              position: 'absolute', left: xOf(s.rect.L), width: spanW(s.rect.L, s.rect.R),
              bottom: 0, height: s.rect.h * UNIT,
              background: 'rgba(251,146,60,0.28)',
              borderTop: `2px dashed ${C.orange}`, borderLeft: `2px dashed ${C.orange}`, borderRight: `2px dashed ${C.orange}`,
              display: 'flex', alignItems: 'center', justifyContent: 'center',
              pointerEvents: 'none', zIndex: 4,
              transition: 'all 0.4s cubic-bezier(0.4,0,0.2,1)',
            }}>
              <span style={{
                fontFamily: mono, fontSize: 11, fontWeight: 700, color: C.text,
                background: C.bg + 'cc', padding: '1px 5px', borderRadius: 4, whiteSpace: 'nowrap',
              }}>{s.h}×{s.w}={s.area}</span>
            </div>
          )}
        </div>

        {/* indices + pointer */}
        <div style={{ position: 'relative', height: 46 }}>
          {Array.from({ length: slots }, (_, k) => {
            const isI = k === s.i && !s.finished;
            const isSent = k === n;
            return (
              <div key={k} style={{
                position: 'absolute', left: xOf(k), width: COL_W, top: 4,
                display: 'flex', flexDirection: 'column', alignItems: 'center', gap: 2,
              }}>
                <span style={{ fontFamily: mono, fontSize: 9, color: isSent ? C.dim + '99' : C.dim }}>{isSent ? 'n' : k}</span>
                {isI && (
                  <>
                    <span style={{ fontFamily: mono, fontSize: 9, fontWeight: 700, color: C.purple }}>▲</span>
                    <span style={{ fontFamily: mono, fontSize: 8, fontWeight: 700, color: C.purple, whiteSpace: 'nowrap' }}>i</span>
                  </>
                )}
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
}

function StackStrip({ H, s }) {
  const n = H.length;
  const cell = (k, kind) => {
    const col = kind === 'popped' ? C.orange : kind === 'top' ? C.accent : C.dim;
    return (
      <div key={`${kind}-${k}`} style={{
        minWidth: 38, padding: '4px 6px', borderRadius: 6, textAlign: 'center',
        background: kind === 'popped' ? C.orangeGlow : kind === 'top' ? C.accentGlow : C.surface2,
        border: `1px ${kind === 'popped' ? 'dashed' : 'solid'} ${kind === 'base' ? C.border : col + '66'}`,
        opacity: kind === 'popped' ? 0.85 : 1,
        transition: 'all 0.3s',
      }}>
        <div style={{ fontFamily: mono, fontSize: 12, fontWeight: 700, color: kind === 'base' ? C.text : col, textDecoration: kind === 'popped' ? 'line-through' : 'none' }}>{k}</div>
        <div style={{ fontFamily: mono, fontSize: 8, color: C.dim }}>h={k === n ? 0 : H[k]}</div>
      </div>
    );
  };

  return (
    <div style={{ padding: '0 16px 12px' }}>
      <div style={{ fontFamily: mono, fontSize: 9, color: C.dim, letterSpacing: 1, marginBottom: 6 }}>
        STACK (bottom → top) · heights increase left → right
      </div>
      <div style={{
        display: 'flex', alignItems: 'center', gap: 5, flexWrap: 'wrap', minHeight: 40,
        padding: 6, borderRadius: 8, background: C.bg, border: `1px solid ${C.border}`,
      }}>
        {s.stack.length === 0 && s.popped === null && (
          <span style={{ fontFamily: mono, fontSize: 11, color: C.dim, padding: '0 6px' }}>[ empty ]</span>
        )}
        {s.stack.map((k, idx) => cell(k, idx === s.stack.length - 1 && s.popped === null ? 'top' : 'base'))}
        {s.popped !== null && (
          <>
            <span style={{ fontFamily: mono, fontSize: 10, color: C.orange, padding: '0 2px' }}>← pop</span>
            {cell(s.popped, 'popped')}
          </>
        )}
      </div>
    </div>
  );
}

