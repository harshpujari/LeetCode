function parseHeights(text) {
  const tokens = text.split(/[\s,\[\]]+/).filter(Boolean);
  if (tokens.length > MAX_BARS) return { error: `At most ${MAX_BARS} bars, please (got ${tokens.length}).` };
  const out = [];
  for (const t of tokens) {
    if (!/^\d+$/.test(t)) return { error: `"${t}" is not a non-negative integer.` };
    const n = Number(t);
    if (n > MAX_VALUE) return { error: `Heights up to ${MAX_VALUE} only, so the chart stays readable (got ${n}).` };
    out.push(n);
  }
  return { value: out };
}

