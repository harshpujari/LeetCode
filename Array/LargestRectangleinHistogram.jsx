// Steps — generated by running the exact algorithm on the input.
//   • one step per pop  (a rectangle gets measured)
//   • one step per push (after the while loop stops)
//
// Example trace for the default input [2,1,5,6,2,3]:
//   i  curr  action                          area   max
//   0   2    push 0                            -      0
//   1   1    pop 0 → h=2 w=1                   2      2
//   1   1    push 1                            -      2
//   2   5    push 2                            -      2
//   3   6    push 3                            -      2
//   4   2    pop 3 → h=6 w=1                   6      6
//   4   2    pop 2 → h=5 w=2                  10     10
//   4   2    push 4                            -     10
//   5   3    push 5                            -     10
//   6   0    pop 5 → h=3 w=1                   3     10
//   6   0    pop 4 → h=2 w=4                   8     10
//   6   0    pop 1 → h=1 w=6                   6     10
//   6   0    push 6 (sentinel)                 -     10
//   return 10
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
function buildSteps(H) {
  const n = H.length;
  const steps = [];
  const stack = [];
  const done = new Set();          // indices already popped (their rectangle is measured)
  let maxArea = 0;
  let best = null;                 // { L, R, h, area } — the rectangle behind max_area

  const snap = (extra) => ({
    i: -1, curr: null, stack: [...stack], done: [...done],
    max_area: maxArea, best: best ? { ...best } : null,
    popped: null, rect: null, h: null, w: null, area: null, newMax: false,
    calc: null, finished: false,
    ...extra,
  });

  steps.push(snap({
    title: "Initial Setup",
    desc:
      `heights has ${n} bar${n === 1 ? '' : 's'}. Key idea: the best rectangle that uses bar k at its full height stretches left and right until it hits a shorter bar on each side. ` +
      `The stack keeps indices whose heights are increasing from bottom to top. When a shorter bar arrives at i, it is the right wall for every taller bar on top of the stack, and the element just below each popped bar is its left wall. ` +
      `The loop runs one extra time with i = n and curr = 0 (a "sentinel"), which is shorter than everything and so flushes whatever is left on the stack.`,
    codeHL: [1, 2, 3],
  }));

  for (let i = 0; i <= n; i++) {
    const curr = i === n ? 0 : H[i];
    let firstPop = true;
    const sentinel = i === n;

    while (stack.length && curr < H[stack[stack.length - 1]]) {
      const top = stack.pop();
      const h = H[top];
      const below = stack.length ? stack[stack.length - 1] : null;
      const w = below === null ? i : i - below - 1;
      const L = below === null ? 0 : below + 1;
      const area = h * w;
      const newMax = area > maxArea;
      if (newMax) { maxArea = area; best = { L, R: i - 1, h, area }; }
      done.add(top);

      const why = sentinel
        ? `i = n = ${n}, so curr is the sentinel 0, which is shorter than heights[${top}] = ${h}.`
        : `curr = heights[${i}] = ${curr} is shorter than the top of the stack, heights[${top}] = ${h}.`;
      const rightWall = sentinel
        ? `There is no shorter bar to its right, so the right wall is the end of the array (i = ${n}).`
        : `So bar ${top} can't stretch past index ${i}: i = ${i} is its right wall.`;
      const leftWall = below === null
        ? `The stack is now empty, which means no bar on the left is shorter than ${h}, so the rectangle reaches all the way to index 0: w = i = ${i}.`
        : `The new top of the stack is index ${below} (height ${H[below]}), the nearest bar on the left that is not taller. Every bar strictly between ${below} and ${i} is at least ${h} tall, so w = i − stack[-1] − 1 = ${i} − ${below} − 1 = ${w}.` +
          (H[below] === h ? ` (heights[${below}] equals h, so this width is short — but index ${below} is still on the stack and will measure the wider rectangle when it is popped later.)` : '');
      const verdict = newMax
        ? ` Area = ${h} × ${w} = ${area}, a new max 🎉 so max_area becomes ${area}.`
        : ` Area = ${h} × ${w} = ${area}, not more than max_area = ${maxArea}.`;

      steps.push(snap({
        title: `i=${i}${sentinel ? ' (sentinel)' : ''} — pop ${top}: h=${h}, w=${w} → area ${area}${newMax ? ' ★' : ''}`,
        desc: `${why} ${rightWall} Pop it: h = ${h}. ${leftWall}${verdict}`,
        i, curr, popped: top, h, w, area, newMax,
        rect: { L, R: i - 1, h },
        calc: {
          label: below === null ? 'w = i   (stack empty)' : 'w = i - stack[-1] - 1',
          value: below === null ? `w = ${i}` : `w = ${i} − ${below} − 1 = ${w}`,
          note: `h × w = ${h} × ${w} = ${area}`,
        },
        codeHL: firstPop ? [4, 5, 7, 8, 9, 10] : [7, 8, 9, 10],
      }));
      firstPop = false;
    }

    // while loop has stopped → push i
    const topBefore = stack.length ? stack[stack.length - 1] : null;
    stack.push(i);

    let desc;
    if (sentinel) {
      desc = n === 0
        ? `heights is empty, so the loop runs only once, with the sentinel i = 0 and curr = 0. The stack is empty, so nothing is popped. stack.append(0) is harmless; the loop ends.`
        : topBefore === null
          ? `The sentinel has flushed the stack, so every bar has had its rectangle measured. stack.append(${n}) runs too, but it is harmless: the loop is over.`
          : `The sentinel has popped every bar taller than 0. What's left on the stack has height 0, and curr = 0 is not < 0, so the while loop stops. That's fine: a zero-height bar can only make a rectangle of area 0. stack.append(${n}) is harmless; the loop is over.`;
    } else if (topBefore === null) {
      desc = (firstPop
        ? `i = ${i}, curr = ${curr}. The stack is empty, so there is nothing to compare against. `
        : `The stack is empty now, so the while loop stops. `) +
        `Push ${i}. Bar ${i}'s right wall is still unknown; it waits on the stack until a shorter bar shows up.`;
    } else {
      const eq = curr === H[topBefore];
      desc = (firstPop ? `i = ${i}, curr = ${curr}. ` : `The while loop stops: `) +
        `curr = ${curr} ${eq ? '=' : '>'} heights[${topBefore}] = ${H[topBefore]}, so the stack stays increasing and nothing is popped. Push ${i}; its right wall is still unknown.` +
        (eq ? ` (Equal heights don't pop. Bar ${topBefore} keeps waiting and will later be measured with a width that includes bar ${i}.)` : '');
    }

    steps.push(snap({
      title: sentinel
        ? `i=${i} (sentinel) — ${topBefore === null ? 'stack empty' : 'only 0-height bars left'} → push ${i}, loop ends`
        : `i=${i} — curr=${curr}${firstPop ? '' : ' after pops'} → push ${i}`,
      desc,
      i, curr,
      codeHL: firstPop ? [4, 5, 7, 11] : [7, 11],
    }));
  }

  steps.push(snap({
    title: `Result: ${maxArea} ✓`,
    desc: n === 0
      ? `No bars means no rectangle. return max_area = 0.`
      : best === null
        ? `Every bar has height 0, so nothing was ever popped and every rectangle has area 0. return max_area = 0.`
        : `Every index is pushed once and popped at most once, so the whole thing is O(n) time even with the inner while loop. ` +
          `The largest rectangle has height ${best.h} and spans indices ${best.L}…${best.R} (width ${best.R - best.L + 1}): area ${best.area}. return max_area = ${maxArea}.`,
    i: n, curr: 0, finished: true,
    codeHL: [12],
  }));
  return steps;
}

