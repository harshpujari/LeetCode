const COL_W = 32, GAP = 6, UNIT = 28;
const LEVELS = MAX_H + 1;           // one unit of headroom
const CHART_H = LEVELS * UNIT;
const xOf = (i) => i * (COL_W + GAP);

function ElevationChart({ s }) {
  const { left, right, left_max, right_max, cur, waterAt, done } = s;
  const totalW = N * COL_W + (N - 1) * GAP;

  return (
    <div style={{ overflowX: 'auto', padding: '20px 16px 8px' }}>
      <div style={{ width: totalW, margin: '0 auto' }}>

        {/* bars + water */}
        <div style={{ position: 'relative', height: CHART_H, borderBottom: `1px solid ${C.border}` }}>
          {/* horizontal grid lines */}
          {Array.from({ length: LEVELS }, (_, k) => (
            <div key={k} style={{
              position: 'absolute', left: 0, right: 0, bottom: k * UNIT,
              borderTop: `1px dashed ${C.border}55`,
            }} />
          ))}

          {/* left_max line: spans [0, left] */}
          {!done && (
            <div style={{
              position: 'absolute', left: 0, width: xOf(left) + COL_W,
              bottom: left_max * UNIT - 1, borderTop: `2px dashed ${C.accent}`,
              transition: 'all 0.4s cubic-bezier(0.4,0,0.2,1)', zIndex: 2,
            }}>
              <span style={{ position: 'absolute', left: 0, top: -16, fontFamily: mono, fontSize: 9, fontWeight: 700, color: C.accent }}>
                left_max={left_max}
              </span>
            </div>
          )}
          {/* right_max line: spans [right, N-1] */}
          {!done && (
            <div style={{
              position: 'absolute', left: xOf(right), right: 0,
              bottom: right_max * UNIT - 1, borderTop: `2px dashed ${C.orange}`,
              transition: 'all 0.4s cubic-bezier(0.4,0,0.2,1)', zIndex: 2,
            }}>
              <span style={{ position: 'absolute', right: 0, top: -16, fontFamily: mono, fontSize: 9, fontWeight: 700, color: C.orange, whiteSpace: 'nowrap' }}>
                right_max={right_max}
              </span>
            </div>
          )}

          {HEIGHT.map((h, i) => {
            const isCur = i === cur;
            const between = i > left && i < right;
            const wtr = waterAt[i] || 0;

            let barBorder, barBg;
            if (done)          { barBorder = C.dim;   barBg = C.surface2; }
            else if (isCur)    { barBorder = C.purple; barBg = C.purpleGlow; }
            else if (between)  { barBorder = C.border + '60'; barBg = 'transparent'; }
            else               { barBorder = C.dim;   barBg = C.surface2; }

            return (
              <div key={i} style={{ position: 'absolute', left: xOf(i), bottom: 0, width: COL_W }}>
                {/* water above the bar */}
                {wtr > 0 && (
                  <div style={{
                    position: 'absolute', bottom: h * UNIT, left: 0, width: COL_W, height: wtr * UNIT,
                    background: done ? C.greenGlow : isCur ? 'rgba(56,189,248,0.35)' : C.accentGlow,
                    border: `1px solid ${done ? C.green : C.accent}${isCur ? '' : '88'}`,
                    borderBottom: 'none', borderRadius: '4px 4px 0 0',
                    display: 'flex', alignItems: 'center', justifyContent: 'center',
                    fontFamily: mono, fontSize: 11, fontWeight: 700,
                    color: done ? C.green : C.accent,
                    filter: isCur ? `drop-shadow(0 0 10px ${C.accentGlow})` : 'none',
                    transition: 'all 0.4s cubic-bezier(0.4,0,0.2,1)',
                  }}>{wtr}</div>
                )}
                {/* the bar itself */}
                {h > 0 && (
                  <div style={{
                    position: 'absolute', bottom: 0, left: 0, width: COL_W, height: h * UNIT,
                    background: barBg, border: `2px solid ${barBorder}`, borderBottom: 'none',
                    borderRadius: '5px 5px 0 0',
                    display: 'flex', alignItems: 'flex-start', justifyContent: 'center', paddingTop: 4,
                    fontFamily: mono, fontSize: 11, fontWeight: 700,
                    color: isCur ? C.purple : between ? C.dim + '80' : C.text,
                    filter: isCur ? `drop-shadow(0 0 12px ${C.purpleGlow})` : 'none',
                    transition: 'all 0.4s cubic-bezier(0.4,0,0.2,1)',
                  }}>{h}</div>
                )}
                {/* settled marker for zero-height bars */}
                {h === 0 && isCur && (
                  <div style={{ position: 'absolute', bottom: 0, left: 0, width: COL_W, height: 3, background: C.purple, borderRadius: 2 }} />
                )}
              </div>
            );
          })}
        </div>

        {/* indices + pointers */}
        <div style={{ position: 'relative', height: 50 }}>
          {HEIGHT.map((_, i) => {
            const isL = i === left, isR = i === right;
            let tag = null;
            if (isL && isR) tag = { label: 'L = R', color: C.green };
            else if (isL)   tag = { label: 'left',  color: C.accent };
            else if (isR)   tag = { label: 'right', color: C.orange };
            return (
              <div key={i} style={{
                position: 'absolute', left: xOf(i), width: COL_W, top: 4,
                display: 'flex', flexDirection: 'column', alignItems: 'center', gap: 2,
              }}>
                <span style={{ fontFamily: mono, fontSize: 9, color: C.dim }}>{i}</span>
                {tag && (
                  <>
                    <span style={{ fontFamily: mono, fontSize: 9, fontWeight: 700, color: tag.color }}>▲</span>
                    <span style={{ fontFamily: mono, fontSize: 8, fontWeight: 700, color: tag.color, letterSpacing: 0.5, whiteSpace: 'nowrap' }}>{tag.label}</span>
                  </>
                )}
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
}

