// Steps — generated by running the exact algorithm on the input,
// one step per while-loop iteration.
//
// Example trace for the default input
// (side = which pointer moved, max = that side's max after update):
//   it  side  idx  h  max  +water  total
//    1   L     1  1   1    0     0
//    2   R    10  2   2    0     0
//    3   L     2  0   1    1     1
//    4   L     3  2   2    0     1
//    5   R     9  1   2    1     2
//    6   R     8  2   2    0     2
//    7   R     7  3   3    0     2
//    8   L     4  1   2    1     3
//    9   L     5  0   2    2     5
//   10   L     6  1   2    1     6
//   11   L     7  3   3    0     6
//   return 6
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
function buildSteps(H) {
  const N = H.length;

  // `if not height: return 0`
  if (N === 0) {
    return [{
      title: "Result: 0 units of water ✓",
      desc: "height is empty, so the early return fires and the function returns 0. There are no bars, so there is nothing to trap.",
      left: 0, right: -1, left_max: 0, right_max: 0, water: 0,
      cur: -1, side: null, add: 0, newMax: false,
      waterAt: [], calc: null, done: true,
      codeHL: [1, 2],
    }];
  }

  const steps = [];
  let l = 0, r = N - 1;
  let lm = H[l], rm = H[r];
  let w = 0;
  const waterAt = Array(N).fill(null);

  steps.push({
    title: "Initial Setup",
    desc: `height has ${N} bar${N === 1 ? '' : 's'}. Two pointers start at the ends: left = 0, right = ${N - 1}. left_max = height[0] = ${lm} and right_max = height[${N - 1}] = ${rm} track the tallest wall seen from each side. The water above any bar is min(tallest wall on its left, tallest wall on its right) − its own height. The two-pointer trick is to always process the side whose max is smaller, because that max is guaranteed to be the min.`,
    left: l, right: r, left_max: lm, right_max: rm, water: w,
    cur: -1, side: null, add: 0, newMax: false,
    waterAt: [...waterAt], calc: null, done: false,
    codeHL: [4, 5, 6],
  });

  let it = 0;
  while (l < r) {
    it++;
    if (lm < rm) {
      const lmBefore = lm;
      l += 1;
      lm = Math.max(lm, H[l]);
      const add = lm - H[l];
      w += add;
      waterAt[l] = add;
      const newMax = H[l] > lmBefore;
      steps.push({
        title: `#${it} — left_max < right_max → move left to ${l}`,
        desc:
          `left_max (${lmBefore}) < right_max (${rm}), so the left side is the bottleneck. Some wall on the right is at least ${rm} tall, so water on this side is capped by left_max alone. Move left to ${l} (height ${H[l]}). ` +
          (newMax
            ? `This bar is taller than the old left_max, so left_max becomes ${lm}. A new tallest wall holds no water above itself: ${lm} − ${H[l]} = 0.`
            : `left_max stays ${lm}. Water here = left_max − height = ${lm} − ${H[l]} = ${add}${add > 0 ? ` 💧, so the total becomes ${w}.` : '.'}`),
        left: l, right: r, left_max: lm, right_max: rm, water: w,
        cur: l, side: 'L', add, newMax,
        waterAt: [...waterAt], done: false,
        calc: { label: 'water += left_max - height[left]', value: `${lm} − ${H[l]} = ${add}`, note: `∴ water → ${w}` },
        codeHL: [8, 9, 10, 11, 12],
      });
    } else {
      const rmBefore = rm;
      r -= 1;
      rm = Math.max(rm, H[r]);
      const add = rm - H[r];
      w += add;
      waterAt[r] = add;
      const newMax = H[r] > rmBefore;
      steps.push({
        title: `#${it} — left_max ≥ right_max → move right to ${r}`,
        desc:
          `left_max (${lm}) ≥ right_max (${rmBefore}), so the right side is the bottleneck. Some wall on the left is at least ${lm} tall, so water on this side is capped by right_max alone. Move right to ${r} (height ${H[r]}). ` +
          (newMax
            ? `This bar is taller than the old right_max, so right_max becomes ${rm}. A new tallest wall holds no water above itself: ${rm} − ${H[r]} = 0.`
            : `right_max stays ${rm}. Water here = right_max − height = ${rm} − ${H[r]} = ${add}${add > 0 ? ` 💧, so the total becomes ${w}.` : '.'}`),
        left: l, right: r, left_max: lm, right_max: rm, water: w,
        cur: r, side: 'R', add, newMax,
        waterAt: [...waterAt], done: false,
        calc: { label: 'water += right_max - height[right]', value: `${rm} − ${H[r]} = ${add}`, note: `∴ water → ${w}` },
        codeHL: [8, 13, 14, 15, 16],
      });
    }
  }

  steps.push({
    title: `Result: ${w} unit${w === 1 ? '' : 's'} of water ✓`,
    desc: N === 1
      ? `With a single bar, left = right = 0 from the start, so the loop never runs. One bar has no walls on both sides to hold water, so the result is 0.`
      : `left = right = ${l}, so the loop ends. The pointers always meet at a tallest bar (height ${H[l]} here), because the pointer standing on it never moves, and a tallest bar can't hold water itself. Return water = ${w}. Each bar was visited once, giving O(n) time and O(1) space with no prefix-max arrays.`,
    left: l, right: r, left_max: lm, right_max: rm, water: w,
    cur: -1, side: null, add: 0, newMax: false,
    waterAt: [...waterAt], calc: null, done: true,
    codeHL: [8, 18],
  });
  return steps;
}

