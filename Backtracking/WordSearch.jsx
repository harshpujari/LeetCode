// Main App
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
export default function App() {
  const [input, setInput] = useState(DEFAULT);
  const [boardText, setBoardText] = useState(boardToText(DEFAULT.board));
  const [wordText, setWordText] = useState(DEFAULT.word);
  const [error, setError] = useState(null);
  const [step, setStep] = useState(0);

  const STEPS = useMemo(() => buildSteps(input.board, input.word), [input]);
  const total = STEPS.length;
  const s = STEPS[Math.min(step, total - 1)];

  const load = ({ board, word }) => {
    setInput({ board, word });
    setBoardText(boardToText(board));
    setWordText(word);
    setError(null);
    setStep(0);
  };

  const run = () => {
    const res = parseInput(boardText, wordText);
    if (res.error) { setError(res.error); return; }
    load(res.value);
  };

  useEffect(() => {
    const handle = (e) => {
      if (e.target instanceof HTMLInputElement && e.target.type === 'text') return;
      if (e.key === 'ArrowRight' || e.key === ' ') {
        e.preventDefault();
        setStep(p => Math.min(p + 1, total - 1));
      }
      if (e.key === 'ArrowLeft') {
        e.preventDefault();
        setStep(p => Math.max(p - 1, 0));
      }
    };
    window.addEventListener('keydown', handle);
    return () => window.removeEventListener('keydown', handle);
  }, [total]);

  const LEGEND = [
    { color: C.green,  label: "on path (marked '#')" },
    { color: C.purple, label: 'match' },
    { color: C.red,    label: 'mismatch / off board' },
    { color: C.orange, label: "hit '#' / backtrack" },
    { color: C.accent, label: 'outer-loop start' },
  ];

  const atStart = step === 0;
  const atEnd = step >= total - 1;
  const accentFor = s.kind === 'result' ? (s.result ? C.green : C.red) : s.kind && PROBE_STYLE[s.kind] ? PROBE_STYLE[s.kind].color : C.accent;

  return (
    <div style={{ background: C.bg, minHeight: '100vh', color: C.text, fontFamily: sans, padding: '20px 12px' }}>
      <style>{`
        @import url('https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@400;600;700&display=swap');
        * { box-sizing: border-box; margin: 0; padding: 0; }
        ::-webkit-scrollbar { height: 6px; }
        ::-webkit-scrollbar-track { background: ${C.surface}; border-radius: 3px; }
        ::-webkit-scrollbar-thumb { background: ${C.border}; border-radius: 3px; }
        input[type=range] { -webkit-appearance: none; width: 100%; height: 6px;
          background: ${C.border}; border-radius: 3px; outline: none; }
        input[type=range]::-webkit-slider-thumb { -webkit-appearance: none;
          width: 18px; height: 18px; border-radius: 50%;
          background: ${C.accent}; cursor: pointer;
          box-shadow: 0 0 8px ${C.accentGlow}; }
        input[type=range]::-moz-range-thumb { width: 18px; height: 18px;
          border-radius: 50%; background: ${C.accent}; cursor: pointer;
          border: none; box-shadow: 0 0 8px ${C.accentGlow}; }
        input[type=text]:focus { border-color: ${C.accent}88 !important; }
      `}</style>

      <div style={{ maxWidth: 960, margin: '0 auto' }}>

        {/* Header */}
        <div style={{ marginBottom: 20 }}>
          <h1 style={{ fontFamily: mono, fontSize: 17, fontWeight: 700, color: C.accent, letterSpacing: -0.3, marginBottom: 4 }}>Word Search</h1>
          <p style={{ fontSize: 13, color: C.dim }}>
            word = "{input.word}" &nbsp;&middot;&nbsp; {input.board.length}×{input.board[0].length} board &nbsp;&middot;&nbsp; DFS + Backtracking &nbsp;&middot;&nbsp; Use &larr; &rarr; keys or buttons
          </p>
        </div>

        <InputPanel
          boardText={boardText} setBoardText={setBoardText}
          wordText={wordText} setWordText={setWordText}
          error={error} onRun={run} onPreset={load} current={input}
        />

        {/* Step title + counter */}
        <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: 14, gap: 12 }}>
          <div style={{ fontFamily: mono, fontSize: 14, fontWeight: 700, color: C.text }}>{s.title}</div>
          <div style={{
            fontFamily: mono, fontSize: 11, color: C.dim, flexShrink: 0,
            background: C.surface, padding: '3px 10px', borderRadius: 6,
          }}>Step {step + 1} / {total}</div>
        </div>

        {/* Main: Board + Word | State Panel */}
        <div style={{ display: 'flex', flexWrap: 'wrap', gap: 12, marginBottom: 16, alignItems: 'stretch' }}>
          <div style={{
            flex: '1 1 440px', minWidth: 0,
            background: C.surface, border: `1px solid ${C.border}`, borderRadius: 12, overflow: 'hidden',
          }}>
            <div style={{
              padding: '8px 14px', borderBottom: `1px solid ${C.border}`,
              fontFamily: mono, fontSize: 10, color: C.dim, letterSpacing: 2, textTransform: 'uppercase',
            }}>Board · {input.board.length}×{input.board[0].length}</div>

            <BoardGrid B={input.board} s={s} />
            <WordStrip word={input.word} s={s} />

            <div style={{
              display: 'flex', gap: 14, flexWrap: 'wrap', justifyContent: 'center',
              padding: '2px 12px 16px', fontFamily: mono, fontSize: 10,
            }}>
              {LEGEND.map(({ color, label }) => (
                <div key={label} style={{ display: 'flex', alignItems: 'center', gap: 5 }}>
                  <div style={{ width: 8, height: 8, borderRadius: 2, background: color }} />
                  <span style={{ color: C.dim }}>{label}</span>
                </div>
              ))}
            </div>
          </div>

          <div style={{ width: 230, flexShrink: 0, flexGrow: 1, maxWidth: '100%' }}>
            <StatePanel B={input.board} word={input.word} s={s} />
          </div>
        </div>

        {/* Description */}
        <div style={{
          background: C.surface,
          borderTop: `1px solid ${C.border}`, borderRight: `1px solid ${C.border}`, borderBottom: `1px solid ${C.border}`,
          borderLeft: `3px solid ${accentFor}`,
          borderRadius: '0 10px 10px 0',
          padding: '14px 18px', marginBottom: 16,
        }}>
          <p style={{ fontSize: 13, color: C.dim, lineHeight: 1.7, fontFamily: sans }}>{s.desc}</p>
        </div>

        {/* Code Panel */}
        <div style={{ marginBottom: 20 }}>
          <CodePanel highlighted={s.codeHL} />
        </div>

        {/* Controls */}
        <div style={{ background: C.surface, border: `1px solid ${C.border}`, borderRadius: 12, padding: '16px 20px' }}>
          <div>
            <input
              type="range" min={0} max={Math.max(total - 1, 0)} value={step}
              onChange={(e) => setStep(Number(e.target.value))}
              style={{ width: '100%' }}
            />
          </div>

          <div style={{ display: 'flex', justifyContent: 'center', gap: 12, marginTop: 14 }}>
            <button
              onClick={() => setStep(0)}
              disabled={atStart}
              style={{
                fontFamily: mono, fontSize: 11, fontWeight: 600,
                padding: '8px 14px', borderRadius: 8,
                background: C.surface2, color: atStart ? C.dim : C.text,
                border: `1px solid ${C.border}`, cursor: atStart ? 'default' : 'pointer',
                transition: 'all 0.2s',
              }}
            >Reset</button>

            <button
              onClick={() => setStep(Math.max(0, step - 1))}
              disabled={atStart}
              style={{
                fontFamily: mono, fontSize: 12, fontWeight: 600,
                padding: '8px 20px', borderRadius: 8,
                background: atStart ? C.surface2 : C.accent + '20',
                color: atStart ? C.dim : C.accent,
                border: `1px solid ${atStart ? C.border : C.accent + '40'}`,
                cursor: atStart ? 'default' : 'pointer',
                transition: 'all 0.2s',
              }}
            >&larr; Prev</button>

            <button
              onClick={() => setStep(Math.min(total - 1, step + 1))}
              disabled={atEnd}
              style={{
                fontFamily: mono, fontSize: 12, fontWeight: 600,
                padding: '8px 20px', borderRadius: 8,
                background: atEnd ? C.surface2 : C.accent,
                color: atEnd ? C.dim : '#0a0e17',
                border: `1px solid ${atEnd ? C.border : C.accent}`,
                cursor: atEnd ? 'default' : 'pointer',
                transition: 'all 0.2s',
              }}
            >Next &rarr;</button>
          </div>
        </div>

        <p style={{ textAlign: 'center', fontSize: 11, color: C.border, marginTop: 16, fontFamily: mono }}>
          &larr; &rarr; arrow keys &nbsp;&middot;&nbsp; spacebar = next
        </p>
      </div>
    </div>
  );
}
