function StatePanel({ B, word, s }) {
  const rows = B.length, cols = B[0].length;
  const pr = s.probe;
  const ps = pr ? PROBE_STYLE[s.kind] : null;
  const dash = '—';
  const inside = pr && pr.r >= 0 && pr.r < rows && pr.c >= 0 && pr.c < cols;
  // board[r][c] as dfs sees it: '#' if on the path (match marks it after the check, so show the letter there)
  let cellVal = dash;
  if (pr && s.kind !== 'found') {
    if (!inside) cellVal = 'off board';
    else if (s.kind === 'visited') cellVal = "'#'";
    else cellVal = `'${B[pr.r][pr.c]}'`;
  }

  // call stack: matched frames + the call being examined
  const frames = s.path;
  const showTop = pr && s.kind !== 'match' && s.kind !== 'back';

  return (
    <div style={{
      background: C.surface, border: `1px solid ${C.border}`, borderRadius: 10, overflow: 'hidden',
      display: 'flex', flexDirection: 'column', height: '100%',
    }}>
      <div style={{
        padding: '8px 14px', borderBottom: `1px solid ${C.border}`,
        fontFamily: mono, fontSize: 10, color: C.dim, letterSpacing: 2, textTransform: 'uppercase', flexShrink: 0,
      }}>Algo State</div>

      <div style={{ padding: '12px 14px', display: 'flex', flexDirection: 'column', gap: 8, flex: 1 }}>
        <VarRow name="(r, c)"      value={pr ? `(${pr.r}, ${pr.c})` : dash} color={ps?.color || C.purple} glow={ps?.glow || C.purpleGlow} active={!!pr} />
        <VarRow name="index"       value={s.index ?? dash} color={C.purple} glow={C.purpleGlow} active={s.index !== null && s.kind !== 'result'} />
        <VarRow name="word[index]" value={s.index !== null && s.index < word.length ? `'${word[s.index]}'` : s.kind === 'found' ? 'end' : dash} color={C.purple} glow={C.purpleGlow} active={s.index !== null && s.kind !== 'result'} />
        <VarRow name="board[r][c]" value={cellVal} color={ps?.color || C.text} glow={ps?.glow || C.surface2} active={!!pr && s.kind !== 'found'} />
        <VarRow name="dfs calls"   value={s.calls} color={C.accent} glow={C.accentGlow} active={false} />

        <div style={{ marginTop: 4 }}>
          <div style={{ fontFamily: mono, fontSize: 9, color: C.dim, letterSpacing: 1, marginBottom: 5 }}>CALL STACK (top ↑)</div>
          <div style={{ display: 'flex', flexDirection: 'column-reverse', gap: 3 }}>
            {s.kind !== 'result' && frames.map((f, k) => {
              const isTop = !showTop && k === frames.length - 1;
              return (
                <div key={k} style={{
                  fontFamily: mono, fontSize: 10, padding: '3px 8px', borderRadius: 5,
                  background: isTop ? ps?.glow || C.greenGlow : C.surface2,
                  border: `1px solid ${isTop ? (ps?.color || C.green) + '55' : C.border}`,
                  color: isTop ? ps?.color || C.green : C.green,
                  display: 'flex', justifyContent: 'space-between',
                }}>
                  <span>dfs({f.r},{f.c},{k})</span><span>'{f.ch}'</span>
                </div>
              );
            })}
            {s.kind === 'back' && (
              <div style={{
                fontFamily: mono, fontSize: 10, padding: '3px 8px', borderRadius: 5,
                background: C.orangeGlow, border: `1px solid ${C.orange}55`, color: C.orange,
                display: 'flex', justifyContent: 'space-between', textDecoration: 'line-through',
              }}>
                <span>dfs({pr.r},{pr.c},{s.index})</span><span>False</span>
              </div>
            )}
            {showTop && (
              <div style={{
                fontFamily: mono, fontSize: 10, padding: '3px 8px', borderRadius: 5,
                background: ps.glow, border: `1px solid ${ps.color}55`, color: ps.color,
                display: 'flex', justifyContent: 'space-between',
              }}>
                <span>dfs({pr.r},{pr.c},{s.index})</span><span>{s.kind === 'found' ? 'True' : 'False'}</span>
              </div>
            )}
            {(s.kind === 'result' || (!frames.length && !pr)) && (
              <div style={{ fontFamily: mono, fontSize: 10, color: C.dim, padding: '3px 8px' }}>[ empty ]</div>
            )}
          </div>
        </div>

        {s.kind === 'result' && (
          <div style={{
            padding: '10px 10px', borderRadius: 6, textAlign: 'center',
            background: s.result ? C.greenGlow : C.redGlow,
            border: `1px solid ${s.result ? C.green : C.red}44`,
          }}>
            <div style={{ fontFamily: mono, fontSize: 13, fontWeight: 700, color: s.result ? C.green : C.red }}>return {s.result ? 'True' : 'False'} ✓</div>
            <div style={{ fontFamily: mono, fontSize: 9, color: C.dim, marginTop: 3, letterSpacing: 0.5 }}>"{word}" {s.result ? 'EXISTS' : 'NOT FOUND'}</div>
          </div>
        )}
      </div>
    </div>
  );
}

