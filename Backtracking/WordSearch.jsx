// Steps — generated by running the exact algorithm on the input.
//   • one step per dfs() call (what that call's checks decide)
//   • one step when a call has tried all 4 directions and backtracks
//   • the outer loop's non-matching cells are grouped into one "scan" step
//   • once True is found it short-circuits every `or` upward; that unwinding
//     is shown in the final result step
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
function buildSteps(B, word) {
  const rows = B.length, cols = B[0].length, L = word.length;
  const board = B.map(r => [...r]);
  const steps = [];
  const path = [];                  // cells currently marked '#', in order
  let calls = 0;
  let scan = null;                  // outer-loop cell {r, c}
  let skipped = [];                 // outer-loop cells grouped into a scan step

  const cellStr = (r, c) => `(${r},${c})`;
  const push = (extra) => {
    if (steps.length >= MAX_STEPS) throw new Error(`This input needs more than ${MAX_STEPS} steps, which is too many to step through. Try a smaller board or shorter word.`);
    steps.push({
      path: path.map(p => ({ ...p })), probe: null, kind: null, index: null,
      calls, scan, skipped: [], result: null, ...extra,
    });
  };

  push({
    title: 'Initial Setup',
    desc:
      `board is ${rows}×${cols}, word = "${word}" (${L} letter${L === 1 ? '' : 's'}). The outer loop tries every cell as a starting point. From a start, dfs(r, c, index) checks whether word[index:] can be spelled starting at (r, c), walking up/down/left/right. ` +
      `While a cell is on the current path it is overwritten with '#', so the same path can't use it twice. When a path fails, the letter is put back (backtracking) so a different path can use it.`,
    codeHL: [1],
  });

  const flushSkips = () => {
    if (!skipped.length) return;
    const list = skipped.map(p => cellStr(p.r, p.c));
    const shown = list.length > 6 ? `${list.slice(0, 3).join(', ')} … ${list.slice(-2).join(', ')}` : list.join(', ');
    push({
      title: `scan — ${skipped.length} cell${skipped.length === 1 ? '' : 's'} ≠ '${word[0]}' → skip`,
      desc: `Outer loop: ${shown} ${skipped.length === 1 ? 'does' : 'do'} not hold word[0] = '${word[0]}', so \`board[r][c] == word[0]\` is False and the \`and\` short-circuits. dfs is never called for ${skipped.length === 1 ? 'it' : 'them'}.`,
      skipped: skipped.map(p => ({ ...p })), scan: skipped[skipped.length - 1],
      codeHL: [18, 19, 20],
    });
    skipped = [];
  };

  let foundPath = null;

  function dfs(r, c, index, dir, pr, pc) {
    calls++;
    const entry = dir ? [dir.line] : [20];
    const via = dir ? `${dir.arrow} ${dir.name} from ${cellStr(pr, pc)}` : `start`;
    const nextTry = (d) => {
      const k = DIRS.indexOf(d);
      return k < 3 ? `back in ${cellStr(pr, pc)}, the \`or\` moves on to ${DIRS[k + 1].name}.` : `that was ${cellStr(pr, pc)}'s last direction (left).`;
    };

    if (index === L) {
      const off = r < 0 || r >= rows || c < 0 || c >= cols;
      foundPath = path.map(p => ({ ...p }));
      push({
        title: `dfs${cellStr(r, c).replace(')', `,${index})`)} — index == len(word) → True ✓`,
        desc: `${via}: index = ${index} == len(word), so all ${L} letters have been matched along the green path. Return True. ` +
          `This check runs before the bounds check, so ${cellStr(r, c)} itself is never looked at${off ? ' (here it is even off the board, and that is fine)' : ''}.`,
        probe: { r, c }, kind: 'found', index, codeHL: [...entry, 4, 5],
      });
      return true;
    }

    if (r < 0 || r >= rows || c < 0 || c >= cols) {
      const why = r < 0 ? 'r < 0' : r >= rows ? `r >= rows (${rows})` : c < 0 ? 'c < 0' : `c >= cols (${cols})`;
      push({
        title: `dfs${cellStr(r, c).replace(')', `,${index})`)} — off the board → False`,
        desc: `${via}: ${why}, so ${cellStr(r, c)} is outside the board. Return False; ${nextTry(dir)}`,
        probe: { r, c }, kind: 'oob', index, codeHL: [...entry, 4, 6, 8],
      });
      return false;
    }

    const ch = board[r][c];
    if (ch !== word[index]) {
      const visited = ch === '#';
      push({
        title: `dfs${cellStr(r, c).replace(')', `,${index})`)} — ${visited ? `'#' (on path)` : `'${ch}' ≠ '${word[index]}'`} → False`,
        desc: visited
          ? `${via}: board${cellStr(r, c).replace('(', '[').replace(',', '][').replace(')', ']')} is '#', because ${cellStr(r, c)} (letter '${B[r][c]}') is already on the current path. A cell can't be used twice, and '#' never equals a letter, so the same \`!= word[index]\` check rejects it. No separate visited set needed. Return False; ${nextTry(dir)}`
          : `${via}: word[${index}] = '${word[index]}' but board[${r}][${c}] = '${ch}'. Return False; ${nextTry(dir)}`,
        probe: { r, c }, kind: visited ? 'visited' : 'mismatch', index, codeHL: [...entry, 4, 6, 7, 8],
      });
      return false;
    }

    // match
    board[r][c] = '#';
    path.push({ r, c, ch });
    push({
      title: `dfs${cellStr(r, c).replace(')', `,${index})`)} — '${ch}' == word[${index}] ✓ mark '#'`,
      desc:
        `${via}: board[${r}][${c}] = '${ch}' matches word[${index}]` + (dir ? '' : ` (guaranteed: the outer loop already checked it)`) + `, letter ${index + 1} of ${L}. ` +
        `Save temp = '${ch}' and overwrite the cell with '#' so this path can't come back to it. Then try the 4 neighbours in order: down, up, right, left. ` +
        (index === L - 1 ? `That was the last letter, so the very next call gets index ${L} == len(word).` : `Each neighbour must match word[${index + 1}] = '${word[index + 1]}'.`),
      probe: { r, c }, kind: 'match', index, codeHL: [...entry, 4, 6, 7, 9, 10],
    });

    let found = false;
    for (const d of DIRS) {
      if (dfs(r + d.dr, c + d.dc, index + 1, d, r, c)) { found = true; break; }
    }
    board[r][c] = ch;
    path.pop();

    if (!found) {
      push({
        title: `dfs${cellStr(r, c).replace(')', `,${index})`)} — all 4 failed → restore '${ch}', False`,
        desc:
          `None of the 4 neighbours of ${cellStr(r, c)} could continue "${word.slice(0, index + 1)}…". Backtrack: board[${r}][${c}] = temp puts '${ch}' back, so other paths are free to use this cell, then return False ` +
          (dir ? `to ${cellStr(pr, pc)}, ${DIRS.indexOf(dir) < 3 ? `which moves on to ${DIRS[DIRS.indexOf(dir) + 1].name}.` : `which has now tried all its directions too.`}` : `to the outer loop, which moves on to the next start cell.`),
        probe: { r, c }, kind: 'back', index, codeHL: [15, 16],
      });
    }
    return found;
  }

  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      if (B[r][c] !== word[0]) { skipped.push({ r, c }); continue; }
      flushSkips();
      scan = { r, c };
      if (dfs(r, c, 0, null)) {
        const pathStr = foundPath.map(p => `'${p.ch}'${cellStr(p.r, p.c)}`).join(' → ');
        push({
          title: 'Result: true ✓',
          desc: `True short-circuits every \`or\` on the way back up. Each frame still runs board[r][c] = temp before returning, so the board ends exactly as it started. The outer loop returns True. Path: ${pathStr}. ${calls} dfs call${calls === 1 ? '' : 's'} in total.`,
          path: foundPath, scan, kind: 'result', result: true, codeHL: [15, 16, 20, 21],
        });
        return steps;
      }
    }
  }
  flushSkips();
  scan = null;
  push({
    title: 'Result: false ✓',
    desc: calls === 0
      ? `No cell holds word[0] = '${word[0]}', so dfs was never called. return False.`
      : `Every cell holding '${word[0]}' was tried as a start and every path failed, so "${word}" can't be spelled. return False after ${calls} dfs call${calls === 1 ? '' : 's'}.`,
    kind: 'result', result: false, codeHL: [22],
  });
  return steps;
}

function parseInput(boardText, wordText) {
  let rowsArr;
  const t = boardText.trim();
  if (!t) return { error: 'Board is empty.' };
  if (t.startsWith('[')) {
    try {
      const j = JSON.parse(t);
      if (!Array.isArray(j) || !j.every(Array.isArray)) throw new Error();
      rowsArr = j.map(row => row.map(String).join(''));
    } catch { return { error: 'Board JSON should look like [["A","B"],["C","D"]].' }; }
  } else {
    rowsArr = t.split(/[;\n]/).map(s => s.replace(/[\s,"']/g, '')).filter(Boolean);
  }
  if (rowsArr.length > MAX_DIM) return { error: `At most ${MAX_DIM} rows (got ${rowsArr.length}).` };
  for (const row of rowsArr) {
    if (!/^[A-Za-z]+$/.test(row)) return { error: `Row "${row}" must contain letters only.` };
    if (row.length > MAX_DIM) return { error: `At most ${MAX_DIM} columns (row "${row}" has ${row.length}).` };
    if (row.length !== rowsArr[0].length) return { error: 'All rows must have the same length.' };
  }
  const word = wordText.trim();
  if (!word) return { error: 'Word is empty.' };
  if (!/^[A-Za-z]+$/.test(word)) return { error: 'Word must contain letters only.' };
  if (word.length > MAX_WORD) return { error: `Word up to ${MAX_WORD} letters (got ${word.length}).` };
  const board = rowsArr.map(row => row.split(''));
  try { buildSteps(board, word); } catch (e) { return { error: e.message }; }
  return { value: { board, word } };
}

