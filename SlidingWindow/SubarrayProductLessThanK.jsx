// Steps — generated by running the exact algorithm on the input.
//   valid r        → 1 step  (extend + count)
//   invalid r      → 1 step "too big" + 1 step per shrink + 1 count step
//
// Example trace for the default input (nums = [10, 5, 2, 6], k = 100):
//   r=0: product=10            window [10]       count += 1 → 1
//   r=1: product=50            window [10,5]     count += 2 → 3
//   r=2: product=100 ≥ 100 ✗   shrink: //10 → 10, l=1
//                              window [5,2]      count += 2 → 5
//   r=3: product=60            window [5,2,6]    count += 3 → 8
//   return 8
//
// groups: cumulative list of [l, r] windows whose "ending at r"
//         subarrays have been counted.
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
const fmt = (arr) => `[${arr.join(', ')}]`;

function endingAt(nums, l, r) {
  const out = [];
  for (let s = r; s >= l; s--) out.push(fmt(nums.slice(s, r + 1)));
  return out.join(', ');
}

function buildSteps(nums, k) {
  const N = nums.length;

  // `if k <= 1: return 0`
  if (k <= 1) {
    return [{
      title: "Result: 0 subarrays ✓",
      desc: `k = ${k} ≤ 1. Every number is ≥ 1, so every product is ≥ 1 and can never be strictly less than ${k}. The early return fires and the answer is 0 without scanning anything.`,
      l: 0, r: -1, product: 1, count: 0, phase: 'done',
      groups: [], done: true,
      calc: { label: 'if k <= 1', value: `${k} <= 1 → True`, note: '∴ return 0', color: 'red' },
      codeHL: [1, 2],
    }];
  }

  const steps = [];
  let product = 1, l = 0, count = 0;
  const groups = [];

  steps.push({
    title: "Initial Setup",
    desc: `nums = ${fmt(nums)}, k = ${k}. k > 1, so the early return is skipped. Every number is ≥ 1, so multiplying in a new element can only keep the product the same or make it larger. That monotonic property is what makes a sliding window work: grow the window on the right, and whenever the product reaches k, shrink it from the left until it's valid again.`,
    l, r: -1, product, count, phase: 'init',
    groups: [], calc: null, done: false,
    codeHL: [0, 1, 3, 4, 5],
  });

  for (let r = 0; r < N; r++) {
    const before = product;
    product *= nums[r];

    if (product < k) {
      const add = r - l + 1;
      count += add;
      groups.push([l, r]);
      steps.push({
        title: `r = ${r} — extend with ${nums[r]}`,
        desc: `product = ${before} × ${nums[r]} = ${product}. ${product} < ${k}, so the while loop doesn't run. The window is ${fmt(nums.slice(l, r + 1))} (l = ${l}, r = ${r}). Every subarray that ends at r and starts anywhere in [l, r] is valid, and there are r − l + 1 = ${add} of them: ${endingAt(nums, l, r)}. Each start position gives exactly one new subarray, which is why we add the window length rather than 1. count = ${count}.`,
        l, r, product, count, phase: 'count',
        groups: [...groups], done: false,
        calc: { label: 'count += r - l + 1', value: `${r} − ${l} + 1 = ${add}`, note: `∴ count → ${count}`, color: 'green' },
        codeHL: [6, 7, 8, 11],
      });
      continue;
    }

    // product >= k: window is too big
    steps.push({
      title: `r = ${r} — extend with ${nums[r]} → too big`,
      desc: `product = ${before} × ${nums[r]} = ${product}. The problem asks for product strictly less than k, and ${product} is not < ${k}, so the window ${fmt(nums.slice(l, r + 1))} is invalid. Because every number is ≥ 1, any window that still starts at l = ${l} and ends at r is also too big. We have to move l to the right.`,
      l, r, product, count, phase: 'invalid',
      groups: [...groups], done: false,
      calc: { label: 'while product >= k', value: `${product} >= ${k} → True`, note: '∴ shrink from the left', color: 'red' },
      codeHL: [7, 8],
    });

    while (product >= k) {
      const drop = nums[l];
      const pb = product;
      product = Math.floor(product / drop);
      l += 1;
      const still = product >= k;
      let tail;
      if (still) {
        tail = `${product} is still ≥ ${k}, so the while loop runs again. One removal isn't always enough, because the new element can be much larger than the one dropped.`;
      } else if (l > r) {
        tail = `${product} < ${k}, so shrinking stops, but the window is now empty (l = ${l} > r = ${r}). Even nums[${r}] = ${nums[r]} on its own is ≥ k, so no subarray ends at index ${r}.`;
      } else {
        tail = `${product} < ${k}, so shrinking stops. The window is now ${fmt(nums.slice(l, r + 1))}. Integer division is exact here because nums[l] is always a factor of the current product.`;
      }
      steps.push({
        title: `r = ${r} — shrink: drop ${drop}`,
        desc: `Divide out the leftmost element: product //= nums[${l - 1}] → ${pb} // ${drop} = ${product}, then l = ${l}. ${tail}`,
        l, r, product, count, phase: still ? 'invalid' : 'shrink',
        groups: [...groups], done: false,
        calc: {
          label: 'product //= nums[l]',
          value: `${pb} // ${drop} = ${product}`,
          note: still ? `∴ l → ${l} · still ≥ ${k}, keep shrinking` : `∴ l → ${l} · ${product} < ${k}, stop`,
          color: still ? 'red' : 'accent',
        },
        codeHL: [8, 9, 10],
      });
    }

    const add = r - l + 1;
    count += add;
    if (add > 0) groups.push([l, r]);
    steps.push({
      title: `r = ${r} — count subarrays ending at ${r}`,
      desc: add > 0
        ? `The window ${fmt(nums.slice(l, r + 1))} is valid. The subarrays ending at r = ${r} are ${endingAt(nums, l, r)}, so r − l + 1 = ${r} − ${l} + 1 = ${add}. Anything that starts left of l contains an element that was dropped, so it isn't counted. count = ${count}.`
        : `l = ${l} is past r = ${r}, so r − l + 1 = 0 and nothing ending at index ${r} is valid. count stays ${count}. On the next r, the window starts fresh from l = ${l}.`,
      l, r, product, count, phase: 'count',
      groups: [...groups], done: false,
      calc: { label: 'count += r - l + 1', value: `${r} − ${l} + 1 = ${add}`, note: `∴ count → ${count}`, color: add > 0 ? 'green' : 'accent' },
      codeHL: [11],
    });
  }

  const all = groups.flatMap(([gl, gr]) => {
    const out = [];
    for (let s = gr; s >= gl; s--) out.push(fmt(nums.slice(s, gr + 1)));
    return out;
  });
  steps.push({
    title: `Result: ${count} subarray${count === 1 ? '' : 's'} ✓`,
    desc: `The loop has finished, so we return count = ${count}.` +
      (count > 0 && count <= 15 ? ` The valid subarrays are ${all.join(', ')}.` : '') +
      ` Both r and l only move forward, so each index enters and leaves the window at most once. That gives O(n) time with O(1) space. The brute force tries every start index and runs in O(n²).`,
    l, r: N - 1, product, count, phase: 'done',
    groups: [...groups], done: true,
    calc: null,
    codeHL: [12],
  });
  return steps;
}

