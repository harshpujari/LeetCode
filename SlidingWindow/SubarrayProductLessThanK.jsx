function parseInput(numsText, kText) {
  const tokens = numsText.split(/[\s,\[\]]+/).filter(Boolean);
  if (tokens.length === 0) return { error: 'Enter at least one number for nums.' };
  if (tokens.length > MAX_LEN) return { error: `At most ${MAX_LEN} numbers, please (got ${tokens.length}).` };
  const nums = [];
  for (const t of tokens) {
    if (!/^\d+$/.test(t) || Number(t) < 1) return { error: `"${t}" must be a positive integer (the algorithm relies on nums[i] ≥ 1).` };
    const n = Number(t);
    if (n > MAX_NUM) return { error: `nums values up to ${MAX_NUM} only (got ${n}).` };
    nums.push(n);
  }
  const kt = kText.trim();
  if (!/^\d+$/.test(kt)) return { error: `k must be a non-negative integer (got "${kt}").` };
  const k = Number(kt);
  if (k > MAX_K) return { error: `k up to ${MAX_K} only (got ${k}).` };
  return { value: { nums, k } };
}

