function NodeBox({ id, s }) {
  const n = NODES[id];
  const isRemoved = s.removed.includes(id);
  const isProbe = s.probe === id;
  const isResult = s.done && !isRemoved && !n.dummy;
  const visible = !n.dummy || s.showDummy;

  let color = C.accent;
  if (n.dummy) color = C.dim;
  if (isProbe) color = n.val === VAL ? C.red : C.orange;
  if (isRemoved) color = C.red + '66';
  if (isResult) color = C.green;

  const nx = s.next[id];
  const nextAddr = nx === null ? 'NULL' : NODES[nx].addr;
  const label = n.dummy ? 'dummy' : id === '0' ? `head · ${n.addr}` : n.addr;

  return (
    <div style={{
      position: 'absolute', left: colX(n.col), top: ROW_Y + (isRemoved ? DROP : 0),
      width: NW, transition: T, zIndex: 2,
      opacity: !visible ? 0 : isRemoved ? 0.4 : 1,
    }}>
      <div style={{
        height: ADDR_H, textAlign: 'center', fontFamily: mono, fontSize: 10, fontWeight: 700,
        color: n.dummy ? C.dim : isRemoved ? C.red : C.purple, letterSpacing: 0.5, whiteSpace: 'nowrap',
      }}>{label}</div>
      <div style={{
        position: 'relative',
        display: 'grid', gridTemplateColumns: '1fr 1fr', height: BH,
        border: `2px ${n.dummy || isRemoved ? 'dashed' : 'solid'} ${color}`,
        borderRadius: 8, overflow: 'visible',
        boxShadow: isProbe || isResult ? `0 0 16px ${color}55` : 'none',
        transition: T,
      }}>
        <div style={{
          padding: '7px 4px 5px', textAlign: 'center', borderRadius: '6px 0 0 6px',
          background: isResult ? C.greenGlow : isProbe ? color + '26' : C.surface2,
          borderRight: `1px solid ${C.border}`, transition: T,
        }}>
          <div style={{
            fontFamily: mono, fontSize: 16, fontWeight: 700,
            color: n.dummy ? C.dim : isRemoved ? C.red : n.val === VAL ? C.orange : C.green,
            textDecoration: isRemoved ? 'line-through' : 'none',
          }}>{n.val}</div>
          <div style={{ fontFamily: mono, fontSize: 6.5, color: C.dim, letterSpacing: 1.5, marginTop: 1 }}>DATA</div>
        </div>
        <div style={{ padding: '7px 4px 5px', textAlign: 'center', background: C.surface, borderRadius: '0 6px 6px 0' }}>
          <div style={{
            fontFamily: mono, fontSize: 9.5, fontWeight: 600, lineHeight: '18px',
            color: nx === null ? C.nullC : s.bypass === id ? C.green : C.orange, transition: T,
          }}>{nextAddr}</div>
          <div style={{ fontFamily: mono, fontSize: 6.5, color: C.dim, letterSpacing: 1.5, marginTop: 1 }}>NEXT</div>
        </div>
        {isRemoved && (
          <div style={{ position: 'absolute', top: -9, right: -3, fontFamily: mono, fontSize: 11, fontWeight: 700, color: C.red }}>✗</div>
        )}
      </div>
    </div>
  );
}

