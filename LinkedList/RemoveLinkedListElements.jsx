// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
// Problem Data
// head = [6, 1, 6, 6, 2, 6], val = 6  →  [1, 2]
// Chosen to hit every edge case: removing the head, removing
// consecutive nodes, and removing the tail.
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
const VAL = 6;
const VALUES = [6, 1, 6, 6, 2, 6];
const ADDRS = ['0x1A', '0x2B', '0x3C', '0x4D', '0x5E', '0x6F'];
// Node ids: 'D' = dummy, 0..5 = list nodes, null = None
const NODES = {
  D: { val: 0, addr: '0x00', col: 0, dummy: true },
  ...Object.fromEntries(VALUES.map((v, i) => [i, { val: v, addr: ADDRS[i], col: i + 1 }])),
};
const LIST_IDS = ['D', ...VALUES.map((_, i) => String(i))];
const NULL_COL = 7;

// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
// Layout
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
const NW = 76, STRIDE = 92, ADDR_H = 16, BH = 46, NULL_W = 56;
const ROW_Y = 92, DROP = 92;
const VIS_W = 716, VIS_H = 280;

const colX = (col) => 14 + col * STRIDE;
const BOX_TOP = ROW_Y + ADDR_H;
const BOX_CY = BOX_TOP + BH / 2;
const idX = (id) => id === null ? colX(NULL_COL) : colX(NODES[id].col);
const idCX = (id) => id === null ? colX(NULL_COL) + NULL_W / 2 : idX(id) + NW / 2;
const name = (id) => id === null ? 'None' : id === 'D' ? 'dummy' : `${NODES[id].val} @${NODES[id].addr}`;

// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
// Code Lines
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
const CODE = [
  { t: 'dummy = ListNode(next=head)', ind: 0 },
  { t: 'curr = dummy', ind: 0 },
  { t: '', ind: 0 },
  { t: 'while curr.next:', ind: 0 },
  { t: 'if curr.next.val == val:', ind: 1 },
  { t: 'curr.next = curr.next.next', ind: 2 },
  { t: 'else:', ind: 1 },
  { t: 'curr = curr.next', ind: 2 },
  { t: '', ind: 0 },
  { t: 'return dummy.next', ind: 0 },
];

// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
// Steps — generated by running the algorithm
// Each step tracks:
//   next:    { id: nextId } current next-pointer map
//   removed: ids unlinked so far
//   curr:    id of curr (undefined before assignment)
//   probe:   id of curr.next being compared (highlighted)
//   bypass:  id whose next was just rewired (arc highlighted)
//   showDummy, calc, codeHL, done
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
const chain = (next) => {
  const out = [];
  let p = next.D;
  while (p !== null) { out.push(NODES[p].val); p = next[p]; }
  return out;
};

function buildSteps() {
  const next = {};
  LIST_IDS.forEach((id, i) => { next[id] = i + 1 < LIST_IDS.length ? LIST_IDS[i + 1] : null; });
  const removed = [];
  const snap = (extra) => ({ next: { ...next }, removed: [...removed], showDummy: true, done: false, calc: null, ...extra });

  const steps = [];
  steps.push({
    ...snap({ curr: undefined, codeHL: [], showDummy: false }),
    title: 'Initial List',
    desc: `head = [${VALUES.join(', ')}], val = ${VAL}. Remove every node whose value is ${VAL}. Tricky cases in this input: the head itself must go, two 6s sit back-to-back, and the tail must go too.`,
  });
  steps.push({
    ...snap({ curr: undefined, codeHL: [0] }),
    title: 'Create dummy node',
    desc: 'dummy = ListNode(next=head) — a sentinel placed before head. Every real node now has a predecessor, so deleting the head is no different from deleting any other node.',
  });
  let curr = 'D';
  steps.push({
    ...snap({ curr, codeHL: [1] }),
    title: 'curr = dummy',
    desc: 'curr always stands on the node BEFORE the one being inspected. To delete a node in a singly linked list you must rewire its predecessor, so we look one node ahead via curr.next.',
  });

  let iter = 0;
  while (next[curr] !== null) {
    iter++;
    const probe = next[curr];
    const hit = NODES[probe].val === VAL;
    steps.push({
      ...snap({ curr, probe, codeHL: [3, 4] }),
      title: `Iter ${iter} — Inspect curr.next`,
      desc: `while curr.next — curr.next is ${name(probe)}, not None, so loop. if curr.next.val == val — ${NODES[probe].val} == ${VAL} is ${hit ? 'True: this node must be removed.' : 'False: keep it.'}`,
      calc: {
        label: 'curr.next.val == val',
        result: `${NODES[probe].val} == ${VAL} → ${hit ? 'True' : 'False'}`,
        note: hit ? '→ unlink it' : '→ advance curr',
        color: hit ? C.red : C.green,
      },
    });
    if (hit) {
      const after = next[probe];
      next[curr] = after;
      removed.push(probe);
      const consecutive = after !== null && NODES[after].val === VAL;
      steps.push({
        ...snap({ curr, bypass: curr, codeHL: [5] }),
        title: `Iter ${iter} — Unlink ${NODES[probe].val} @${NODES[probe].addr}`,
        desc: `curr.next = curr.next.next — ${name(curr)}.next now points to ${name(after)}, skipping ${name(probe)}. It is unreachable now and will be garbage collected. curr does NOT move${consecutive ? ' — good thing, because the new curr.next is another 6 that also needs checking.' : ': the new curr.next has not been checked yet.'}`,
      });
    } else {
      curr = probe;
      steps.push({
        ...snap({ curr, codeHL: [6, 7] }),
        title: `Iter ${iter} — Advance curr`,
        desc: `else: curr = curr.next — ${name(curr)} stays in the list, so it is safe to step onto it. It becomes the new predecessor for the next check.`,
      });
    }
  }

  steps.push({
    ...snap({ curr, codeHL: [3] }),
    title: 'Loop check — exit',
    desc: `while curr.next — curr is ${name(curr)} and curr.next is None. Every node has been inspected exactly once, so the loop ends.`,
    calc: { label: 'curr.next', result: 'None', note: '→ exit loop', color: C.purple },
  });
  steps.push({
    ...snap({ curr, codeHL: [9], done: true }),
    title: 'Return dummy.next ✅',
    desc: `return dummy.next — the original head was deleted, so we can't return head; dummy.next always holds the true first node. Result: [${chain(next).join(', ')}]. Time O(n), space O(1).`,
  });
  return steps;
}

const STEPS = buildSteps();

