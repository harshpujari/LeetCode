// Live (reachable) links only: walk from dummy following next pointers.
function Links({ s }) {
  const links = [];
  let p = s.showDummy ? 'D' : '0';
  while (p !== null) {
    const q = s.next[p];
    links.push([p, q]);
    p = q;
  }
  return (
    <svg width={VIS_W} height={VIS_H} style={{ position: 'absolute', left: 0, top: 0, pointerEvents: 'none', zIndex: 1 }}>
      <defs>
        {[['o', C.orange], ['g', C.green]].map(([k, col]) => (
          <marker key={k} id={`rm-${k}`} markerUnits="userSpaceOnUse" markerWidth="9" markerHeight="9" refX="8" refY="4.5" orient="auto">
            <polygon points="0 0, 9 4.5, 0 9" fill={col} />
          </marker>
        ))}
      </defs>
      {links.map(([a, b]) => {
        const x1 = idX(a) + NW, x2 = idX(b) - 3;
        const adjacent = (b === null ? NULL_COL : NODES[b].col) - NODES[a].col === 1;
        const fresh = s.bypass === a;
        const col = adjacent ? C.orange : C.green;
        const d = adjacent
          ? `M ${x1} ${BOX_CY} L ${x2} ${BOX_CY}`
          : `M ${x1} ${BOX_CY - 10} C ${x1 + 34} ${BOX_CY - 82}, ${x2 - 34} ${BOX_CY - 82}, ${x2} ${BOX_CY - 10}`;
        return (
          <path key={`${a}-${b}`} d={d} fill="none" stroke={col}
            strokeWidth={fresh ? 2.5 : 2} opacity={fresh ? 1 : 0.75}
            strokeDasharray={adjacent ? 'none' : '6 4'}
            markerEnd={`url(#rm-${adjacent ? 'o' : 'g'})`}
            style={{ filter: fresh ? `drop-shadow(0 0 6px ${C.greenGlow})` : 'none' }} />
        );
      })}
    </svg>
  );
}

